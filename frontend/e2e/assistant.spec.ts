import { test, expect, signIn } from './fixtures';

test('natural language requisition reaches manager approval and the approved record', async ({page}) => {
  const title = `Natural laboratory supplies ${Date.now()}`;
  const request = `Please create a requisition: supplier: Thermo Fisher; title: ${title}; item: Sterile tubes; quantity: 4; unit price: $12.50; reason: Restock the laboratory`;
  await page.goto('/');
  await signIn(page, 'analyst@procurem.demo');
  await page.getByRole('link',{name:'Assistant',exact:true}).click();
  const input = page.getByLabel('Ask the assistant');
  await input.fill(request);
  const sent = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/assistant/messages' && r.request().method() === 'POST');
  await input.press('Enter');
  const response = await sent;
  expect(response.status()).toBe(200);
  const payload = response.request().postDataJSON();
  expect(payload.message).toBe(request);
  expect(payload.action).toBeUndefined();
  const result = await response.json();
  expect(result.answer.approval_id).toBeGreaterThan(0);
  await expect(page.getByText(result.answer.text,{exact:true})).toBeVisible();
  const link = page.getByRole('link',{name:'View pending approval'});
  await expect(link).toHaveAttribute('href',`/approvals/${result.answer.approval_id}`);
  const loaded = page.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/approvals/${result.answer.approval_id}`);
  await link.click();
  const approvalResponse = await loaded;
  expect(approvalResponse.status()).toBe(200);
  const approval = await approvalResponse.json();
  expect(approval).toMatchObject({status:'pending',risk:'low',approval_type:'requisition',proposed:{title,supplier:'Thermo Fisher',total_amount_usd:'50.00',reason:'Restock the laboratory',lines:[{description:'Sterile tubes',quantity:4,unit_price:'12.50'}]}});
  await expect(page.getByRole('heading',{name:title})).toBeVisible();
  await expect(page.getByText('Thermo Fisher',{exact:true})).toBeVisible();
  await expect(page.getByText('50.00',{exact:true})).toBeVisible();
  await expect(page.getByText('Waiting for signature')).toBeVisible();
  await expect(page.getByRole('button',{name:'Approve'})).toHaveCount(0);

  await page.getByRole('button',{name:'Sign out'}).click();
  await signIn(page, 'proc.manager@procurem.demo');
  const notices = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/notifications' && r.request().method() === 'GET');
  await page.getByRole('link',{name:/^Notifications/}).click();
  const noticesResponse = await notices;
  expect(noticesResponse.status()).toBe(200);
  const items = (await noticesResponse.json()).items;
  const noticeIndex = items.findIndex((item: {link:string}) => item.link === `/approvals/${result.answer.approval_id}`);
  expect(noticeIndex).toBeGreaterThanOrEqual(0);
  await page.getByRole('listitem').nth(noticeIndex).getByRole('button').click();
  await expect(page.getByRole('heading',{name:title})).toBeVisible();
  await page.getByRole('button',{name:'Approve'}).click();
  await page.getByLabel('Reason').fill('Reviewed and approved');
  await page.getByLabel('Password').fill('Demo@1234');
  const signed = page.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/approvals/${result.answer.approval_id}/sign` && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Sign',exact:true}).click();
  const decision = await signed;
  expect(decision.status()).toBe(200);
  expect(await decision.json()).toMatchObject({status:'approved',signatures:[{role:'procurement_manager',meaning:'Approved',reason:'Reviewed and approved'}]});
  await expect(page.getByRole('paragraph').filter({hasText:'Reviewed and approved'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Approve'})).toHaveCount(0);

  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Requisitions',exact:true}).click();
  // The newest requisition may be beyond the first page in the seeded directory.
  const sort = page.getByRole('button',{name:/^Requisition(?: [↑↓])?$/});
  const ascending = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/records/requisitions' && new URL(r.url()).searchParams.get('order') === 'asc');
  await sort.click();
  expect((await ascending).status()).toBe(200);
  await expect(page.getByRole('columnheader',{name:/^Requisition/})).toHaveAttribute('aria-sort','ascending');
  const descending = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/records/requisitions' && new URL(r.url()).searchParams.get('order') === 'desc');
  await sort.click();
  expect((await descending).status()).toBe(200);
  const code = approval.proposed.code;
  const recordResponse = page.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/records/requisitions/${approval.subject_id}`);
  await page.getByRole('link',{name:code,exact:true}).click();
  const record = await recordResponse;
  expect(record.status()).toBe(200);
  expect(await record.json()).toMatchObject({item:{id:approval.subject_id,title,status:'approved',total_amount_usd:'50.00'},relations:{lines:[{description:'Sterile tubes',quantity:4,unit_price:'12.50'}]}});
  await expect(page.getByRole('heading',{name:new RegExp(code)})).toContainText(title);
  await expect(page.getByText('approved',{exact:true})).toBeVisible();
  await expect(page.getByText(/Sterile tubes/)).toBeVisible();
});

