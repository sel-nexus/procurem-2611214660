import { test, expect, signIn } from './fixtures';

test('sourcing specialist proposes an event and a seeded bid award', async ({page}) => {
  test.setTimeout(90_000);
  await page.goto('/');
  await signIn(page,'sourcing@procurem.demo');
  await page.getByRole('link',{name:'Sourcing',exact:true}).click();
  await page.getByRole('button',{name:'Create sourcing event'}).click();
  const title = `Browser event ${Date.now()}`;
  await page.getByLabel('Title').fill(title);
  await page.getByLabel('Event type').selectOption('RFQ');
  await page.getByLabel('Estimated value (USD)').fill('5000');
  await page.getByLabel('End date').fill('2030-12-31');
  const created = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/sourcing' && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Submit for approval'}).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const event = await createResponse.json();
  expect(event.status).toBe('pending_approval');
  await expect(page.getByRole('row').filter({hasText:title})).toBeVisible();
  await expect(page.getByText('Loading records…')).toHaveCount(0);
  await page.getByRole('link',{name:'View pending approval'}).click();
  await expect(page).toHaveURL(new RegExp(`/approvals/${event.approval_id}$`), {timeout: 30_000});
  await expect(page.getByRole('heading',{name:title})).toBeVisible();
  await page.getByRole('link',{name:'Sourcing',exact:true}).click();
  await page.getByRole('link',{name:'SE-3002'}).click();
  await page.getByRole('button',{name:'Request award'}).click();
  await page.getByLabel('Bid').selectOption({index:1});
  const awarded = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/sourcing/2/awards' && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Submit for approval'}).click();
  const awardResponse = await awarded;
  expect(awardResponse.status()).toBe(201);
  const award = await awardResponse.json();
  expect(award.status).toBe('pending');
  await page.getByRole('link',{name:'View pending approval'}).click();
  await expect(page.getByRole('heading',{name:'Award: Sourcing event 2'})).toBeVisible();
  await page.getByRole('button',{name:'Sign out'}).click();
  await signIn(page,'proc.manager@procurem.demo');
  await page.getByRole('link',{name:/^Approvals, \d+ pending$/}).click();
  await page.locator(`a[href="/approvals/${event.approval_id}"]`).click();
  await page.getByRole('button',{name:'Approve'}).click();
  await page.getByLabel('Reason').fill('Event reviewed and approved');
  await page.getByLabel('Password').fill('Demo@1234');
  const eventSigned = page.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/approvals/${event.approval_id}/sign` && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Sign',exact:true}).click();
  const eventDecision = await eventSigned;
  expect(eventDecision.status()).toBe(200);
  expect((await eventDecision.json()).status).toBe('approved');
  await expect(page.getByRole('paragraph').filter({hasText:'Event reviewed and approved'})).toBeVisible();
  await page.getByRole('link',{name:'Sourcing',exact:true}).click();
  await page.locator(`a[href="/sourcing/${event.id}"]`).click();
  await expect(page).toHaveURL(new RegExp(`/sourcing/${event.id}$`));
  await expect(page.getByText('active',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:/^Approvals, \d+ pending$/}).click();
  await page.locator(`a[href="/approvals/${award.approval_id}"]`).click();
  await page.getByRole('button',{name:'Approve'}).click();
  await page.getByLabel('Reason').fill('Award reviewed and approved');
  await page.getByLabel('Password').fill('Demo@1234');
  const signed = page.waitForResponse(r => new URL(r.url()).pathname === `/api/v1/approvals/${award.approval_id}/sign` && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Sign',exact:true}).click();
  const signedResponse = await signed;
  expect(signedResponse.status()).toBe(200);
  expect((await signedResponse.json()).status).toBe('approved');
  await expect(page.getByRole('paragraph').filter({hasText:'Award reviewed and approved'})).toBeVisible();
  await page.getByRole('link',{name:'Sourcing',exact:true}).click();
  await page.getByRole('link',{name:'SE-3002'}).click();
  await expect(page).toHaveURL(/\/sourcing\/2$/);
  await expect(page.getByText('awarded',{exact:true})).toBeVisible();
});
